package compressor_test

// Per-family floor over the bench corpus. The committed table
// testdata/bench/baseline.tsv holds integers only: family, fixtures, raw bytes,
// reduced bytes. TestBenchGuard compares a fresh run (rtk off, CCR column
// ignored) against it; `make bench-baseline` rewrites it. See
// docs/contrib/bench-baseline.md.

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"testing"
)

var baselinePath = filepath.Join("testdata", "bench", "baseline.tsv")

const (
	// A family may lose this many permille (20 = 2.0 points) of saving, and
	// only when its reduced size also grew by more than familyByteSlack bytes.
	// The byte floor keeps one-fixture families of a few hundred bytes from
	// tripping on a one-line change.
	familyTolerancePermille = 20
	familyByteSlack         = 8
	// The lossless, lossy and total figures may lose 0.5 points.
	aggregateTolerancePermille = 5

	rowTotal    = "@total"
	rowLossless = "@lossless"
	rowLossy    = "@lossy"
	regenHint   = "run `make bench-baseline` to accept it, and state the reason in the PR and the CHANGELOG"
)

type baseRow struct {
	family              string
	files, raw, reduced int
}

func (r baseRow) permille() int {
	if r.raw == 0 {
		return 0
	}
	return (r.raw - r.reduced) * 1000 / r.raw
}

func (r baseRow) pct() string { return fmt.Sprintf("%.1f%%", float64(r.permille())/10) }

func isAggregate(family string) bool { return strings.HasPrefix(family, "@") }

// guardRows turns a bench run into the comparable rows: each compacted family
// (not the CCR-only row), then the lossless, lossy and total sums.
func guardRows(rows []benchRow) []baseRow {
	var out []baseRow
	for _, r := range rows {
		if r.family == "TOTAL" || r.family == ccrOnlyFamily {
			continue
		}
		out = append(out, baseRow{r.family, r.files, r.raw, r.reduced})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].family < out[j].family })
	lossless, lossy := classTotals(rows)
	total := rows[len(rows)-1]
	return append(out,
		baseRow{rowLossless, lossless.files, lossless.raw, lossless.reduced},
		baseRow{rowLossy, lossy.files, lossy.raw, lossy.reduced},
		baseRow{rowTotal, total.files, total.raw, total.reduced})
}

func formatBaseline(rows []baseRow) string {
	var b strings.Builder
	b.WriteString("# family\tfixtures\traw_bytes\treduced_bytes\n")
	b.WriteString("# Generated by `make bench-baseline`; rows starting with @ are sums. Do not edit by hand.\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "%s\t%d\t%d\t%d\n", r.family, r.files, r.raw, r.reduced)
	}
	return b.String()
}

func readBaseline(path string) ([]baseRow, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var rows []baseRow
	sc := bufio.NewScanner(f)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimRight(sc.Text(), "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		p := strings.Split(line, "\t")
		if len(p) != 4 {
			return nil, fmt.Errorf("%s:%d: want 4 tab-separated fields, got %d", path, n, len(p))
		}
		v := [3]int{}
		for i := range v {
			if v[i], err = strconv.Atoi(p[i+1]); err != nil {
				return nil, fmt.Errorf("%s:%d: %w", path, n, err)
			}
		}
		rows = append(rows, baseRow{p[0], v[0], v[1], v[2]})
	}
	return rows, sc.Err()
}

// compareBaseline returns one message per violation of the floor; none means ok.
func compareBaseline(base, got []baseRow) []string {
	cur := map[string]baseRow{}
	for _, r := range got {
		cur[r.family] = r
	}
	seen := map[string]bool{}
	var out []string
	for _, b := range base {
		seen[b.family] = true
		g, ok := cur[b.family]
		switch {
		case !ok:
			out = append(out, fmt.Sprintf("%s: family vanished (baseline saving %s); %s", b.family, b.pct(), regenHint))
		case isAggregate(b.family):
			if g.permille() < b.permille()-aggregateTolerancePermille {
				out = append(out, fmt.Sprintf("%s: saving fell from %s to %s; %s", b.family, b.pct(), g.pct(), regenHint))
			}
		default:
			if g.files < b.files {
				out = append(out, fmt.Sprintf("%s: %d fixtures, baseline has %d; %s", b.family, g.files, b.files, regenHint))
			}
			if g.permille() < b.permille()-familyTolerancePermille && g.reduced > b.reduced+familyByteSlack {
				out = append(out, fmt.Sprintf("%s: saving fell from %s to %s (reduced %d to %d bytes); %s", b.family, b.pct(), g.pct(), b.reduced, g.reduced, regenHint))
			}
		}
	}
	for _, g := range got {
		if !seen[g.family] {
			out = append(out, fmt.Sprintf("%s: compacts (saving %s) but has no baseline row; %s", g.family, g.pct(), regenHint))
		}
	}
	return out
}

func TestBenchGuard(t *testing.T) {
	base, err := readBaseline(baselinePath)
	if err != nil {
		t.Fatal(err)
	}
	for _, msg := range compareBaseline(base, guardRows(benchCorpus(t, false))) {
		t.Error(msg)
	}
}

// TestBenchBaselineWrite rewrites the committed table (`make bench-baseline`).
func TestBenchBaselineWrite(t *testing.T) {
	if os.Getenv("DOWNSHIFT_BENCH_BASELINE") == "" {
		t.Skip("set DOWNSHIFT_BENCH_BASELINE=1 (make bench-baseline)")
	}
	text := formatBaseline(guardRows(benchCorpus(t, false)))
	if err := os.WriteFile(baselinePath, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
}
